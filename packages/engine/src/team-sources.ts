// What each team was given: its sources, its tools and the servers and skills
// its definition names, as one Markdown file a team under the plugin's `teams/`, cut from the
// definition by `scripts/build-team-declarations.ts`. This module reads a declaration, cuts it into
// sections and tables, and answers `crew sources`. Nothing here installs or writes.

import { join } from "node:path";
import { readRegular } from "./fs.ts";
import { TEAMS } from "./team.ts";
import type { TeamName } from "./types.ts";

