/** The secrets scan's own cap: the largest declaration is a quarter of it. */
export const DECLARATION_MAX_BYTES = 1024 * 1024;

export const LAST_LINE =
  "Nothing is installed by this command. A row's install line is what its page gave on the day its definition names: the page is read again before the line is run, and who runs it is not decided yet.";

const USAGE = "usage: crew sources [<team> [<n>]] | crew sources backend --project";
const FIRST_SECTION = "\n## 3. ";
const LAST_SECTION = /^## \d+\. What the code needs, not decided here$/m;

/** The cells of one table line. */
export function cells(line: string): string[] {
  return line
    .slice(1, line.endsWith("|") ? -1 : undefined)
    .split("|")
    .map((cell) => cell.trim());
}

/** A line of a table that is not the rule under its header. */
export const isRow = (line: string) => line.startsWith("| ") && !line.startsWith("| :-");

/** The rows of a text's tables, each as its cells, the rule under a header left out and the header kept. */
export function rows(part: string): string[][] {
  return part.split("\n").filter(isRow).map(cells);
}

/**
 * What `declarationLine` removes, by code point, so that no invisible character stands in this file:
 * the control characters, the C1 controls, the zero-width characters and the bidi characters, which
 * are `quotedText`'s ranges.
 */
const REMOVED_RANGES: readonly (readonly [number, number])[] = [
  [0x0000, 0x001f],
  [0x007f, 0x009f],
  [0x200b, 0x200f],
  [0x202a, 0x202e],
  [0x2066, 0x2069],
];

/**
 * A declaration's line as the command prints it: without the characters of `REMOVED_RANGES`, and
 * otherwise whole. A held row says it is held near the end of a line of thousands of characters,
 * and a line's indentation is part of it, so nothing is cut or trimmed.
 */
export function declarationLine(line: string): string {
  let kept = "";
  for (const char of line) {
    const code = char.codePointAt(0) ?? 0;
    if (!REMOVED_RANGES.some(([from, to]) => code >= from && code <= to)) kept += char;
  }
  return kept;
}

/**
 * A definition's text from `## 3. ` to the line before the heading of its last section, under the
 * comment line that names it; null where the definition lacks either heading.
 */
export function cutDeclaration(definition: string, file: string): string | null {
  const from = definition.indexOf(FIRST_SECTION);
  const last = LAST_SECTION.exec(definition);
  if (from < 0 || !last || last.index <= from) return null;
  return `<!-- Generated by scripts/build-team-declarations.ts from docs/specs/${file}: never edited by hand. -->\n${definition.slice(from + 1, last.index)}`;
}

const teamNames = () => Object.keys(TEAMS);
const notATeam = () => `not a team: the teams are ${teamNames().join(", ")}`;

/**
 * A team's declaration under `teams/` of the root given. A name that is no own key of the registry
 * is refused before a path is built, so only the nine names reach the file system; the file is read
 * as a regular file under the cap, never through a link.
 */
export function readTeamDeclaration(
  root: string,
  team: string,
): { path: string; text: string } | { refused: string } {
  if (!Object.hasOwn(TEAMS, team)) return { refused: notATeam() };
  const path = join(root, "teams", `${team}.md`);
  const bytes = readRegular(path, DECLARATION_MAX_BYTES);
  if (bytes === null) return { refused: `${path}: absent or not a regular file` };
  if (bytes === "over cap")
    return { refused: `${path}: over ${DECLARATION_MAX_BYTES / (1024 * 1024)} MiB` };
  return { path, text: bytes.toString("utf8") };
}

export interface DeclarationTable {
  header: string[];
  /** The rows under the header, the header and its rule left out. */
  rows: string[][];
}

export interface DeclarationSection {
  /** From 1, in the file's order, level two and three counted together. */
  number: number;
  level: 2 | 3;
  heading: string;
  /** The heading and what follows it, to the next heading of either level. */
  lines: string[];
  tables: DeclarationTable[];
}

/** The tables of a section's lines: each run of lines that open with a pipe, its first line the header. */
function tablesOf(lines: readonly string[]): DeclarationTable[] {
  const tables: DeclarationTable[] = [];
  let run: string[] = [];
  const close = () => {
    const [header, ...rest] = run;
    if (header !== undefined && rest.length > 0)
      tables.push({ header: cells(header), rows: rest.filter(isRow).map(cells) });
    run = [];
  };
  for (const line of lines) {
    if (line.startsWith("|")) run.push(line);
    else close();
  }
  close();
  return tables;
}

/** A declaration's headings of level two and three in order, each with its own lines and tables. */
export function declarationSections(text: string): DeclarationSection[] {
  const sections: DeclarationSection[] = [];
  let current: { level: 2 | 3; heading: string; lines: string[] } | null = null;
  const close = () => {
    if (current)
      sections.push({ number: sections.length + 1, ...current, tables: tablesOf(current.lines) });
  };
  for (const line of text.split("\n")) {
    const level = line.startsWith("## ") ? 2 : line.startsWith("### ") ? 3 : null;
    if (level !== null) {
      close();
      current = { level, heading: line, lines: [line] };
    } else current?.lines.push(line);
  }
  close();
  return sections;
}

/** One line of a team's index: the number, the heading under its level's indent, each table's count of rows. */
function indexLine(section: DeclarationSection): string {
  const title = declarationLine(section.heading.replace(/^#+ /, ""));
  const counts = section.tables.map((t) => `${t.rows.length} row${t.rows.length === 1 ? "" : "s"}`);
  const tail = counts.length ? ` (${counts.join(", ")})` : "";
  return `${section.number}. ${section.level === 3 ? "  " : ""}${title}${tail}`;
}

export type RowMark = "framework" | "tool" | "by stack" | "not this project's" | "other stack";

export interface ProjectRow {
  mark: RowMark;
  cells: string[];
  /** The row as the declaration holds it. */
  line: string;
}

/** The heading of the one table whose rows are keyed by stack. */
const PER_STACK = "### Per stack, from the framework's or the tool's own team";
/** The stack names of that table's first cell, each to the core's stack, in the declaration's order. */
const STACK_OF: ReadonlyMap<string, string> = new Map([
  ["PHP", "php"],
  ["Node / TypeScript", "node"],
  ["Python", "python"],
  ["Go", "go"],
  ["Rust", "rust"],
]);
/** The core's stacks the table has rows for, in the declaration's order. */
const ROW_STACKS: readonly string[] = [...STACK_OF.values()];
const isLetter = (char: string | undefined) => char !== undefined && /[A-Za-z]/.test(char);

/** The ids of the table that targets show between them. */
function shownIds(targets: readonly Pick<Target, "frameworks">[]): Set<string> {
  return new Set(targets.flatMap((target) => frameworkIds(target.frameworks)));
}

/** Whether a text names a phrase whole: the phrase with a letter on neither side of it. */
function names(text: string, phrase: string): boolean {
  for (let at = text.indexOf(phrase); at >= 0; at = text.indexOf(phrase, at + 1))
    if (!isLetter(text[at - 1]) && !isLetter(text[at + phrase.length])) return true;
  return false;
}

/** The ids of the tools' table that targets show between them. */
function shownTools(targets: readonly Pick<Target, "tools">[]): Set<string> {
  return new Set(targets.flatMap((target) => toolIds(target.tools)));
}

/**
 * The rows of the backend declaration's per-stack table, each marked for a project's targets. For
 * a row of a stack the project has, in this order: a framework of the stack named in its cell
 * decides (`framework` where a target shows one named, else `not this project's`); else a tool of
 * the stack named in its cell decides the same way (`tool`); else a product no manifest shows is
 * `not this project's`; else the row is the project's `by stack`. So a framework's row is a
 * project's whether or not the tool it installs is already there.
 */
export function projectRows(
  declaration: string,
  targets: readonly Pick<Target, "stack" | "frameworks" | "tools">[],
): ProjectRow[] {
  const section = declarationSections(declaration).find((s) => s.heading === PER_STACK);
  // The table's lines after its header: the rows, as the file holds them.
  const lines = (section?.lines ?? []).filter(isRow).slice(1);
  return lines.map((line): ProjectRow => {
    const row = cells(line);
    const stack = STACK_OF.get(row[0] ?? "");
    const mine = targets.filter((target) => target.stack === stack);
    if (stack === undefined || mine.length === 0) return { mark: "other stack", cells: row, line };
    const said = row[1] ?? "";
    const frameworks = FRAMEWORKS.filter((f) => f.stack === stack && names(said, f.name));
    if (frameworks.length) {
      const shown = shownIds(mine);
      const mark = frameworks.some((f) => shown.has(f.id)) ? "framework" : "not this project's";
      return { mark, cells: row, line };
    }
    const tools = TOOLS.filter(
      (tool) => Object.hasOwn(tool.stacks, stack) && names(said, tool.name),
    );
    if (tools.length) {
      const shown = shownTools(mine);
      const mark = tools.some((tool) => shown.has(tool.id)) ? "tool" : "not this project's";
      return { mark, cells: row, line };
    }
    const product = NOT_IN_A_MANIFEST.some((entry) => names(said, entry.name));
    return { mark: product ? "not this project's" : "by stack", cells: row, line };
  });
}

/** The heading of the table whose rows are every stack's, and how its rows for an error service open. */
const COMMON = "### Common to every stack";
const ERROR_SERVICE = "Errors in production: ";

/** The rows of the common table for the error services a project's targets show, as the file holds them, in its order. */
function errorServiceRows(
  declaration: string,
  targets: readonly Pick<Target, "tools">[],
): string[] {
  const section = declarationSections(declaration).find((s) => s.heading === COMMON);
  const shown = shownTools(targets);
  return (section?.lines ?? [])
    .filter(isRow)
    .slice(1)
    .filter((line) => {
      const use = cells(line)[0] ?? "";
      if (!use.startsWith(ERROR_SERVICE)) return false;
      const service = use.slice(ERROR_SERVICE.length);
      return TOOLS.some((tool) => tool.name === service && shown.has(tool.id));
    });
}

/** The targets of a project whose stack the declaration has rows for, detected in memory; null where the folder is in no project. */
function projectTargets(cwd: string): Target[] | null {
  const root = findRoot(cwd);
  if (root === null) return null;
  // No pack's rules: the stacks are the core's five, and nothing is loaded or saved.
  return detectTargets(root).filter((target) => ROW_STACKS.includes(target.stack));
}

/** The lines that describe a project: its stacks with their frameworks, and its tools where it shows any. */
function describedProject(targets: readonly Target[]): string[] {
  const stacks = CORE_STACKS.filter((stack) => targets.some((target) => target.stack === stack));
  const of = (stack: string) => targets.filter((target) => target.stack === stack);
  const frameworks = stacks.map((stack) => {
    const shown = shownIds(of(stack));
    const ids = FRAMEWORKS.filter((f) => shown.has(f.id)).map((f) => f.id);
    return `${stack} (${ids.length ? ids.join(", ") : "no framework of the table"})`;
  });
  const tools = stacks.flatMap((stack) => {
    const shown = shownTools(of(stack));
    const ids = TOOLS.filter((tool) => shown.has(tool.id)).map((tool) => tool.id);
    return ids.length ? [`${stack} (${ids.join(", ")})`] : [];
  });
  return [
    `this project: ${frameworks.join("; ")}`,
    ...(tools.length ? [`tools: ${tools.join("; ")}`] : []),
  ];
}

/** A count with its word: `0 rows`, `1 row`, `2 rows`. */
const rowsCount = (count: number) => `${count} row${count === 1 ? "" : "s"}`;

/** The rows of a project under their headings, what was left out of the per-stack table, and what the command cannot tell. */
function projectRowLines(declaration: string, targets: readonly Target[]): string[] {
  const rows = projectRows(declaration, targets);
  const of = (mark: RowMark) => rows.filter((row) => row.mark === mark);
  const orNone = (lines: string[]) => (lines.length ? lines : ["  none"]);
  const printed = (mark: RowMark) => orNone(of(mark).map((row) => declarationLine(row.line)));
  return [
    "rows for this project's frameworks:",
    ...printed("framework"),
    "rows for the tools this project shows:",
    ...printed("tool"),
    "rows by stack:",
    ...printed("by stack"),
    "error services this project shows:",
    "  a row here adds a server that reaches the service's production data with a credential, and a hosted one sends what a session asks off the machine; where the credential is held and with what scope is not decided: run no line of this section before it is",
    ...orNone(errorServiceRows(declaration, targets).map(declarationLine)),
    `left out: ${rowsCount(of("other stack").length)} of another stack, ${rowsCount(of("not this project's").length)} of a framework, a tool or a product this project does not show`,
    "not told: the rows of the table Common to every stack for source hosting and databases, which depend on a service nothing detects",
  ];
}

/** The lines of `crew sources backend --project`, after the declaration's path. The two short answers hold nothing of a project's rows. */
function projectLines(declaration: string, cwd: string): string[] {
  const targets = projectTargets(cwd);
  if (targets === null)
    return [
      "this folder is in no project (no .git at or above it, no .crew in it): nothing was read of it",
    ];
  if (targets.length === 0)
    return [
      `this project: no target of a stack the declaration has rows for (${ROW_STACKS.join(", ")})`,
    ];
  return [...describedProject(targets), ...projectRowLines(declaration, targets)];
}

/**
 * `crew sources [<team> [<n>]]`: the teams with their files, a team's index, or one section's own
 * lines; `crew sources backend --project`: the rows of the backend's per-stack table that are the
 * project's at `cwd`. Each ends with the fixed last line. A refusal carries no line of a declaration.
 */
export function sourcesCommand(
  root: string,
  args: readonly string[],
  /** `project`: the folder whose project's rows are asked for, with `--project`. */
  options: { project?: { cwd: string } } = {},
): { code: number; text: string } {
  const refuse = (text: string) => ({ code: 1, text });
  const done = (lines: string[]) => ({ code: 0, text: [...lines, LAST_LINE].join("\n") });
  if (args.length > 2) return refuse(USAGE);
  const [team, n] = args;
  // The project's rows are one team's and no section's.
  if (options.project && (team === undefined || n !== undefined)) return refuse(USAGE);
  if (team === undefined) {
    const lines: string[] = [];
    for (const name of teamNames()) {
      const read = readTeamDeclaration(root, name);
      if ("refused" in read) return refuse(read.refused);
      lines.push(`${name}: ${declarationSections(read.text).length} sections, ${read.path}`);
    }
    return done(lines);
  }
  const read = readTeamDeclaration(root, team);
  if ("refused" in read) return refuse(read.refused);
  if (options.project) {
    if (team !== "backend")
      return refuse(
        "only the backend's declaration has rows by stack: crew sources backend --project",
      );
    return done([read.path, ...projectLines(read.text, options.project.cwd)]);
  }
  const sections = declarationSections(read.text);
  if (n === undefined) return done([read.path, ...sections.map(indexLine)]);
  const section = /^[1-9]\d*$/.test(n) ? sections[Number(n) - 1] : undefined;
  if (!section)
    return refuse(
      `${team} has ${sections.length} sections: give a number from 1 to ${sections.length}`,
    );
  return done(section.lines.map(declarationLine));
}
