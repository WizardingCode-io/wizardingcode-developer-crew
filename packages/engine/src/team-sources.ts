/** Why a row of the error services' section is held, whatever its line. */
export const ERROR_SERVICE_HOLD = "it reaches production data with a credential";

/** Why a row of the per-stack table is held, by the order of ADR 0025's table. */
const HOLD = {
  noCommand: "its row gives no command",
  notStable: "not stable by its own row",
  hosted: "hosted, so what a session asks leaves the machine",
  value: "its line takes a value of the machine, a token or a key",
  prompt: "its line is typed at Claude Code's prompt, which a session cannot do",
  noForm: "its line is not one of the engine's install forms",
} as const;

const COMPOSER_REQUIRE = "composer require";
const NOT_STABLE_PHRASES: readonly string[] = ["experimental", "release candidate"];
const NOT_STABLE_TAG = /.@(?:rc|beta|alpha|next|canary)$/;
const VALUE_MARKS: readonly string[] = [
  "$",
  "{",
  "<",
  " -e ",
  " -H ",
  "--env",
  "--header",
  "--token",
  "--api-key",
  "--password",
];
const SHELL_MARKS: readonly string[] = ["|", ";", "&", ">", "\n"];

/** The install lines of a row: the spans between backticks of its last cell, as the file holds them. */
function installSpans(cells: readonly string[]): string[] {
  return [...(cells.at(-1) ?? "").matchAll(/`([^`]*)`/g)].map((match) => match[1] ?? "");
}

/** The form a line opens with, as whole words. */
function formOf(line: string): InstallForm | undefined {
  return INSTALL_FORMS.find(({ form }) => line === form || line.startsWith(`${form} `));
}

/** Why a row is held before its lines' forms are asked, by orders 1 to 5 of ADR 0025's table; null where none holds. */
function holdOf(cells: readonly string[], lines: readonly string[]): string | null {
  if (lines.length === 0) return HOLD.noCommand;
  const some = (test: (line: string) => boolean) => lines.some(test);
  const said = (cell: string | undefined, phrase: string) =>
    names((cell ?? "").toLowerCase(), phrase);
  if (
    cells.some((cell) => NOT_STABLE_PHRASES.some((phrase) => said(cell, phrase))) ||
    some((line) => line.split(" ").some((word) => NOT_STABLE_TAG.test(word)))
  )
    return HOLD.notStable;
  if (
    some((line) => line.includes("http://") || line.includes("https://")) ||
    said(cells[1], "hosted")
  )
    return HOLD.hosted;
  if (some((line) => VALUE_MARKS.some((mark) => line.includes(mark)))) return HOLD.value;
  if (some((line) => line.startsWith("/"))) return HOLD.prompt;
  return null;
}

/** The forms of a row's lines, each once, in the lines' order; null where a line holds a shell's mark or opens with no form (order 6). */
function formsOf(lines: readonly string[]): InstallForm[] | null {
  const forms: InstallForm[] = [];
  for (const line of lines) {
    const form = formOf(line);
    if (form === undefined || SHELL_MARKS.some((mark) => line.includes(mark))) return null;
    if (!forms.includes(form)) forms.push(form);
  }
  return forms;
}

/** The package that alone shows a tool in a stack: undefined where the tool has a second sign, of any kind. */
function onlyPackageOf(tool: (typeof TOOLS)[number], stack: string): string | undefined {
  const signs = Object.hasOwn(tool.stacks, stack) ? tool.stacks[stack] : undefined;
  if (!signs || signs.files?.length || signs.tables?.length) return undefined;
  return signs.dependencies?.length === 1 ? signs.dependencies[0] : undefined;
}

/** Whether a line requires the one package that shows a tool the row's stack already shows. */
function requiresShown(line: string, stack: string, shown: ReadonlySet<string>): boolean {
  if (formOf(line)?.form !== COMPOSER_REQUIRE) return false;
  const words = line.slice(COMPOSER_REQUIRE.length).split(" ").filter(Boolean);
  const required = words.find((word) => !word.startsWith("-"));
  return TOOLS.some((tool) => shown.has(tool.id) && onlyPackageOf(tool, stack) === required);
}

/**
 * The state of a row of the per-stack table, from its own cells and the ids of `TOOLS` that the
 * project's targets of the row's stack show: held with the reason of the first order that holds,
 * in the project already, or ready with the forms of its lines, each once, in their order.
 */
export function rowInstall(cells: readonly string[], shown: ReadonlySet<string>): RowInstall {
  const lines = installSpans(cells);
  const reason = holdOf(cells, lines);
  if (reason !== null) return { state: "held", reason };
  const forms = formsOf(lines);
  if (forms === null) return { state: "held", reason: HOLD.noForm };
  const stack = STACK_OF.get(cells[0] ?? "");
  if (stack !== undefined && lines.some((line) => requiresShown(line, stack, shown)))
    return { state: "in the project already" };
  return { state: "ready", forms };
}

/** The lines printed after a row for its state: the engine's own words alone. */
export function installLines(install: RowInstall): string[] {
  if (install.state === "held") return [`  install: held, ${install.reason}`];
  if (install.state !== "ready") return [`  install: ${install.state}`];
  return ["  install: ready", ...install.forms.map(({ form, note }) => `    ${form}: ${note}`)];
}

/** The heading of the one table whose rows are keyed by stack. */
const PER_STACK = "### Per stack, from the framework's or the tool's own team";
/** The stack names of that table's first cell, each to the core's stack, in the declaration's order. */
const STACK_OF: ReadonlyMap<string, string> = new Map([
  ["PHP", "php"],
  ["Node / TypeScript", "node"],
  ["Python", "python"],
  ["Go", "go"],
  ["Rust", "rust"],
]);
/** The core's stacks the table has rows for, in the declaration's order. */
const ROW_STACKS: readonly string[] = [...STACK_OF.values()];
const isLetter = (char: string | undefined) => char !== undefined && /[A-Za-z]/.test(char);

/** The ids of the table that targets show between them. */
function shownIds(targets: readonly Pick<Target, "frameworks">[]): Set<string> {
  return new Set(targets.flatMap((target) => frameworkIds(target.frameworks)));
}

/** Whether a text names a phrase whole: the phrase with a letter on neither side of it. */
function names(text: string, phrase: string): boolean {
  for (let at = text.indexOf(phrase); at >= 0; at = text.indexOf(phrase, at + 1))
    if (!isLetter(text[at - 1]) && !isLetter(text[at + phrase.length])) return true;
  return false;
}

/** The ids of the tools' table that targets show between them. */
function shownTools(targets: readonly Pick<Target, "tools">[]): Set<string> {
  return new Set(targets.flatMap((target) => toolIds(target.tools)));
}

/**
 * The rows of the backend declaration's per-stack table, each marked for a project's targets. For
 * a row of a stack the project has, in this order: a framework of the stack named in its cell
 * decides (`framework` where a target shows one named, else `not this project's`); else a tool of
 * the stack named in its cell decides the same way (`tool`); else a product no manifest shows is
 * `not this project's`; else the row is the project's `by stack`. So a framework's row is a
 * project's whether or not the tool it installs is already there.
 */
export function projectRows(
  declaration: string,
  targets: readonly Pick<Target, "stack" | "frameworks" | "tools">[],
): ProjectRow[] {
  const section = declarationSections(declaration).find((s) => s.heading === PER_STACK);
  // The table's lines after its header: the rows, as the file holds them.
  const lines = (section?.lines ?? []).filter(isRow).slice(1);
  return lines.map((line): ProjectRow => {
    const row = cells(line);
    const stack = STACK_OF.get(row[0] ?? "");
    const mine = targets.filter((target) => target.stack === stack);
    const tools = shownTools(mine);
    const marked = (mark: RowMark): ProjectRow => ({
      mark,
      cells: row,
      line,
      install: rowInstall(row, tools),
    });
    if (stack === undefined || mine.length === 0) return marked("other stack");
    const said = row[1] ?? "";
    const frameworks = FRAMEWORKS.filter((f) => f.stack === stack && names(said, f.name));
    if (frameworks.length) {
      const shown = shownIds(mine);
      return marked(frameworks.some((f) => shown.has(f.id)) ? "framework" : "not this project's");
    }
    const named = TOOLS.filter(
      (tool) => Object.hasOwn(tool.stacks, stack) && names(said, tool.name),
    );
    if (named.length)
      return marked(named.some((tool) => tools.has(tool.id)) ? "tool" : "not this project's");
    const product = NOT_IN_A_MANIFEST.some((entry) => names(said, entry.name));
    return marked(product ? "not this project's" : "by stack");
  });
}

/** The heading of the table whose rows are every stack's, and how its rows for an error service open. */
const COMMON = "### Common to every stack";
const ERROR_SERVICE = "Errors in production: ";

/** The rows of the common table for the error services a project's targets show, as the file holds them, in its order. */
function errorServiceRows(
  declaration: string,
  targets: readonly Pick<Target, "tools">[],
): string[] {
  const section = declarationSections(declaration).find((s) => s.heading === COMMON);
  const shown = shownTools(targets);
  return (section?.lines ?? [])
    .filter(isRow)
    .slice(1)
    .filter((line) => {
      const use = cells(line)[0] ?? "";
      if (!use.startsWith(ERROR_SERVICE)) return false;
      const service = use.slice(ERROR_SERVICE.length);
      return TOOLS.some((tool) => tool.name === service && shown.has(tool.id));
    });
}

/** A project's root and its targets whose stack the declaration has rows for, detected in memory; null where the folder is in no project. */
function detectedProject(cwd: string): { root: string; targets: Target[] } | null {
  const root = findRoot(cwd);
  if (root === null) return null;
  // No pack's rules: the stacks are the core's five, and nothing is loaded or saved.
  const targets = detectTargets(root).filter((target) => ROW_STACKS.includes(target.stack));
  return { root, targets };
}

/** The lines that describe a project: its stacks with their frameworks, and its tools where it shows any. */
function describedProject(targets: readonly Target[]): string[] {
  const stacks = CORE_STACKS.filter((stack) => targets.some((target) => target.stack === stack));
  const of = (stack: string) => targets.filter((target) => target.stack === stack);
  const frameworks = stacks.map((stack) => {
    const shown = shownIds(of(stack));
    const ids = FRAMEWORKS.filter((f) => shown.has(f.id)).map((f) => f.id);
    return `${stack} (${ids.length ? ids.join(", ") : "no framework of the table"})`;
  });
  const tools = stacks.flatMap((stack) => {
    const shown = shownTools(of(stack));
    const ids = TOOLS.filter((tool) => shown.has(tool.id)).map((tool) => tool.id);
    return ids.length ? [`${stack} (${ids.join(", ")})`] : [];
  });
  return [
    `this project: ${frameworks.join("; ")}`,
    ...(tools.length ? [`tools: ${tools.join("; ")}`] : []),
  ];
}

/** A count with its word: `0 rows`, `1 row`, `2 rows`. */
const rowsCount = (count: number) => `${count} row${count === 1 ? "" : "s"}`;

/** The day of an entry: the first ten characters of its time, which is its day in UTC. */
const dayOf = (entry: SourceEntry) => entry.at.slice(0, 10);

const sameLines = (a: readonly string[], b: readonly string[]) =>
  a.length === b.length && a.every((line, at) => line === b[at]);

/** The entry a record holds for a row of the project team's, by the row's page. */
function entryOf(entries: readonly SourceEntry[], row: ProjectRow): SourceEntry | undefined {
  return entries.find((entry) => entry.team === PROJECT_TEAM && entry.page === row.cells[2]);
}

/**
 * The lines printed after a row for its state, with the record: a ready row with an entry prints
 * the entry's decision and day where its lines are the row's, and ready again, said, where they
 * changed. A held row and a row in the project already print their state whatever the record holds.
 */
function stateLines(row: ProjectRow, entries: readonly SourceEntry[]): string[] {
  const entry = row.install.state === "ready" ? entryOf(entries, row) : undefined;
  if (entry === undefined) return installLines(row.install);
  if (sameLines(entry.lines, installSpans(row.cells)))
    return [`  install: ${entry.decision}, recorded on ${dayOf(entry)}`];
  const [, ...notes] = installLines(row.install);
  return [
    `  install: ready, its line changed since it was recorded as ${entry.decision} on ${dayOf(entry)}`,
    ...notes,
  ];
}

/** The rows of a project under their headings, each with its state, what was left out of the per-stack table, and what the command cannot tell. */
function projectRowLines(
  declaration: string,
  targets: readonly Target[],
  entries: readonly SourceEntry[],
): string[] {
  const rows = projectRows(declaration, targets);
  const of = (mark: RowMark) => rows.filter((row) => row.mark === mark);
  const orNone = (lines: string[]) => (lines.length ? lines : ["  none"]);
  const printed = (mark: RowMark) =>
    orNone(of(mark).flatMap((row) => [declarationLine(row.line), ...stateLines(row, entries)]));
  const held = installLines({ state: "held", reason: ERROR_SERVICE_HOLD });
  return [
    "rows for this project's frameworks:",
    ...printed("framework"),
    "rows for the tools this project shows:",
    ...printed("tool"),
    "rows by stack:",
    ...printed("by stack"),
    "error services this project shows:",
    "  a row here adds a server that reaches the service's production data with a credential, and a hosted one sends what a session asks off the machine; where the credential is held and with what scope is not decided: run no line of this section before it is",
    ...orNone(
      errorServiceRows(declaration, targets).flatMap((line) => [declarationLine(line), ...held]),
    ),
    `left out: ${rowsCount(of("other stack").length)} of another stack, ${rowsCount(of("not this project's").length)} of a framework, a tool or a product this project does not show`,
    "not told: the rows of the table Common to every stack for source hosting and databases, which depend on a service nothing detects",
  ];
}

/** The lines of `crew sources backend --project`, after the declaration's path. The two short answers hold nothing of a project's rows nor of its record. */
function projectLines(declaration: string, cwd: string): string[] {
  const project = detectedProject(cwd);
  if (project === null) return [NO_PROJECT];
  if (project.targets.length === 0)
    return [
      `this project: no target of a stack the declaration has rows for (${ROW_STACKS.join(", ")})`,
    ];
  const record = readSourcesRecord(project.root);
  return [
    ...describedProject(project.targets),
    ...projectRowLines(declaration, project.targets, record.entries),
    ...(record.unread
      ? [
          `the record of installs (${SOURCES_RECORD_NAME}) could not be read as the engine writes it and was not read`,
        ]
      : []),
  ];
}

/** The marks of the rows a project may record: its own, by a framework, a tool or its stack. */
const OWN_MARKS: readonly RowMark[] = ["framework", "tool", "by stack"];
const NOT_RECORDED = {
  place: ".crew/local is not a folder of this project",
  bounds: "the row does not fit the record's bounds",
} as const;

/**
 * `crew sources backend --installed <page> | --declined <page>`: one row of the project's recorded
 * by its page, at the time given. It refuses by the first case of the spec's table that holds, and
 * a refusal prints no row and no character of the page given. `root` is the plugin's folder and
 * `cwd` a folder of the project.
 */
export function recordSourcesCommand(
  root: string,
  args: readonly string[],
  flags: Readonly<Record<string, string | boolean>>,
  cwd: string,
  at: string,
): { code: number; text: string } {
  const refuse = (text: string) => ({ code: 1, text });
  // One of the two flags, and no more: which one is the decision, and its value the page.
  if ((flags.installed === undefined) === (flags.declined === undefined)) return refuse(USAGE);
  const decision = flags.installed === undefined ? "declined" : "installed";
  const page = flags[decision];
  if (typeof page !== "string" || page === "") return refuse(USAGE);
  if (args.length !== 1 || flags.project !== undefined) return refuse(USAGE);
  if (args[0] !== PROJECT_TEAM) return refuse("only the backend's declaration has a project form");
  const read = readTeamDeclaration(root, PROJECT_TEAM);
  if ("refused" in read) return refuse(read.refused);
  const project = detectedProject(cwd);
  // The command reaches here in a project; a caller with a folder in none is told so.
  if (project === null) return refuse(NO_PROJECT);
  if (sourcesPlaceRefused(project.root)) return refuse(`not recorded: ${NOT_RECORDED.place}`);
  const row = projectRows(read.text, project.targets).find(
    (candidate) => OWN_MARKS.includes(candidate.mark) && candidate.cells[2] === page,
  );
  if (row === undefined)
    return refuse(
      "no row of this project is read at that page: crew sources backend --project prints the rows and their pages",
    );
  if (row.install.state === "held")
    return refuse(`not recorded: the row is held, ${row.install.reason}`);
  if (row.install.state === "in the project already")
    return refuse("not recorded: the row is in the project already");
  const recorded = recordSourceRow(
    project.root,
    { team: PROJECT_TEAM, page, decision, lines: installSpans(row.cells) },
    at,
  );
  if (!recorded.ok) return refuse(`not recorded: ${NOT_RECORDED[recorded.why]}`);
  return {
    code: 0,
    text: [
      declarationLine(row.line),
      `recorded: ${recorded.entry.decision} on ${dayOf(recorded.entry)}`,
      ...(recorded.replaced
        ? [`it replaces: ${recorded.replaced.decision} on ${dayOf(recorded.replaced)}`]
        : []),
      ...(recorded.notKept
        ? [
            `the record that stood (${SOURCES_RECORD_NAME}) could not be read as the engine writes it and was not kept`,
          ]
        : []),
      LAST_LINE,
    ].join("\n"),
  };
}

/**
 * `crew sources [<team> [<n>]]`: the teams with their files, a team's index, or one section's own
 * lines; `crew sources backend --project`: the rows of the backend's per-stack table that are the
 * project's at `cwd`. Each ends with the fixed last line. A refusal carries no line of a declaration.
 */
export function sourcesCommand(
  root: string,
  args: readonly string[],
  /** `project`: the folder whose project's rows are asked for, with `--project`. */
  options: { project?: { cwd: string } } = {},
): { code: number; text: string } {
  const refuse = (text: string) => ({ code: 1, text });
  const done = (lines: string[]) => ({ code: 0, text: [...lines, LAST_LINE].join("\n") });
  if (args.length > 2) return refuse(USAGE);
  const [team, n] = args;
  // The project's rows are one team's and no section's.
  if (options.project && (team === undefined || n !== undefined)) return refuse(USAGE);
  if (team === undefined) {
    const lines: string[] = [];
    for (const name of teamNames()) {
      const read = readTeamDeclaration(root, name);
      if ("refused" in read) return refuse(read.refused);
      lines.push(`${name}: ${declarationSections(read.text).length} sections, ${read.path}`);
    }
    return done(lines);
  }
  const read = readTeamDeclaration(root, team);
  if ("refused" in read) return refuse(read.refused);
  if (options.project) {
    if (team !== "backend")
      return refuse(
        "only the backend's declaration has rows by stack: crew sources backend --project",
      );
    return done([read.path, ...projectLines(read.text, options.project.cwd)]);
  }
  const sections = declarationSections(read.text);
  if (n === undefined) return done([read.path, ...sections.map(indexLine)]);
  const section = /^[1-9]\d*$/.test(n) ? sections[Number(n) - 1] : undefined;
  if (!section)
    return refuse(
      `${team} has ${sections.length} sections: give a number from 1 to ${sections.length}`,
    );
  return done(section.lines.map(declarationLine));
}
