const COMPOSER_REQUIRE = "composer require";
const NOT_STABLE_PHRASES: readonly string[] = [
  "experimental",
  "release candidate",
  "beta",
  "preview",
  "pre-release",
  "alpha",
];
/** The words that only join the lines of a last cell, in lower case alone. */
const JOINING_WORDS: readonly string[] = ["then", "and", "or"];
const NOT_STABLE_TAG = /.@(?:rc|beta|alpha|next|canary)$/;
const VALUE_MARKS: readonly string[] = [
  "$",
  "{",
  "<",
  " -e ",
  " -H ",
  "--env",
  "--header",
  "--token",
  "--api-key",
  "--password",
];
const SHELL_MARKS: readonly string[] = ["|", ";", "&", ">", "\n"];

/** The install lines of a row: the spans between backticks of its last cell, as the file holds them. */
function installSpans(cells: readonly string[]): string[] {
  return [...(cells.at(-1) ?? "").matchAll(/`([^`]*)`/g)].map((match) => match[1] ?? "");
}

/** The form a line opens with, as whole words. */
function formOf(line: string): InstallForm | undefined {
  return INSTALL_FORMS.find(({ form }) => line === form || line.startsWith(`${form} `));
}

/** What a row's last cell holds beside its lines: its words outside the spans, the joining words left out. */
function wordsBeside(cells: readonly string[]): string[] {
  return (cells.at(-1) ?? "")
    .replace(/`[^`]*`/g, " ")
    .split(/[\s,;:.]+/)
    .filter((word) => word !== "" && !JOINING_WORDS.includes(word));
}

/** An address in a line: from its scheme, wherever in the line it opens, to a space or the line's end. */
const ADDRESS = /https?:\/\/\S*/g;
/** A GitHub repository's address and nothing after it, the scheme and the host as written here. */
const REPOSITORY_ADDRESS = /^https:\/\/github\.com\/([A-Za-z0-9._-]+)\/([A-Za-z0-9._-]+)$/;
const dotsAlone = (name: string | undefined) => name === undefined || /^\.+$/.test(name);

/**
 * Whether a line holds an address that is no repository's (ADR 0025's amendment of 2026-11-26,
 * item 2026-11-26-002): a repository is fetched as the form with `owner/repo` fetches it, and
 * nothing a session asks is sent to it, so its address does not make a row hosted.
 */
function holdsAnAddress(line: string): boolean {
  return (line.match(ADDRESS) ?? []).some((address) => {
    const [, owner, repository] = REPOSITORY_ADDRESS.exec(address) ?? [];
    return dotsAlone(owner) || dotsAlone(repository);
  });
}

/** Why a row is held before its lines' forms are asked, by orders 1 to 5 of ADR 0025's table and then by what its last cell says beside its lines; null where none holds. `hostedLifted` leaves the hosted order out. */
function holdOf(
  cells: readonly string[],
  lines: readonly string[],
  hostedLifted: boolean,
): string | null {
  if (lines.length === 0) return HOLD.noCommand;
  const some = (test: (line: string) => boolean) => lines.some(test);
  const said = (cell: string | undefined, phrase: string) =>
    names((cell ?? "").toLowerCase(), phrase);
  if (
    cells.some((cell) => NOT_STABLE_PHRASES.some((phrase) => said(cell, phrase))) ||
    some((line) => line.split(" ").some((word) => NOT_STABLE_TAG.test(word)))
  )
    return HOLD.notStable;
  if (!hostedLifted && (some(holdsAnAddress) || said(cells[1], "hosted"))) return HOLD.hosted;
  if (some((line) => VALUE_MARKS.some((mark) => line.includes(mark)))) return HOLD.value;
  if (some((line) => line.startsWith("/"))) return HOLD.prompt;
  if (wordsBeside(cells).length > 0) return HOLD.wordy;
  return null;
}

const SERVER_LINE = "claude mcp add ";
const SCOPES: readonly string[] = ["local", "project", "user"];
const SERVER_NAME = /^[A-Za-z0-9_][A-Za-z0-9_-]*$/;
const SERVER_ADDRESS = /^https:\/\/[A-Za-z0-9.-]+(?::[0-9]+)?(?:\/[^\s"'`\\]*)?$/;

/**
 * A line that adds a hosted server by its address alone, read word by word (item 2026-11-26-005):
 * the transport `http` once, at most one scope, a name and an `https://` address, the options in
 * any place among them, and nothing else. Its form by its scope and its address; undefined where
 * the line is not of that shape.
 */
function serverLine(line: string): { form: InstallForm; address: string } | undefined {
  if (!line.startsWith(SERVER_LINE)) return undefined;
  const words = line.slice(SERVER_LINE.length).split(" ");
  let transport = false;
  let scope: string | undefined;
  const names: string[] = [];
  for (let at = 0; at < words.length; at++) {
    const word = words[at] ?? "";
    if (word === "--transport" || word === "-t") {
      if (transport || words[at + 1] !== "http") return undefined;
      transport = true;
      at++;
    } else if (word === "--scope" || word === "-s") {
      const value = words[at + 1] ?? "";
      if (scope !== undefined || !SCOPES.includes(value)) return undefined;
      scope = value;
      at++;
    } else names.push(word);
  }
  const [name = "", address = "", ...more] = names;
  if (!transport || more.length > 0 || !SERVER_NAME.test(name) || !SERVER_ADDRESS.test(address))
    return undefined;
  const form = SERVER_FORMS[SCOPES.indexOf(scope ?? "local")];
  return form === undefined ? undefined : { form, address };
}

/** The forms of a row's lines, each once, in the lines' order; null where a line holds a shell's mark or opens with no form (order 6). */
function formsOf(lines: readonly string[]): InstallForm[] | null {
  const forms: InstallForm[] = [];
  for (const line of lines) {
    const form = formOf(line) ?? serverLine(line)?.form;
    if (form === undefined || SHELL_MARKS.some((mark) => line.includes(mark))) return null;
    if (!forms.includes(form)) forms.push(form);
  }
  return forms;
}

/** The package that alone shows a tool in a stack: undefined where the tool has a second sign, of any kind. */
function onlyPackageOf(tool: (typeof TOOLS)[number], stack: string): string | undefined {
  const signs = Object.hasOwn(tool.stacks, stack) ? tool.stacks[stack] : undefined;
  if (!signs || signs.files?.length || signs.tables?.length) return undefined;
  return signs.dependencies?.length === 1 ? signs.dependencies[0] : undefined;
}

/** Whether a line requires the one package that shows a tool the row's stack already shows. */
function requiresShown(line: string, stack: string, shown: ReadonlySet<string>): boolean {
  if (formOf(line)?.form !== COMPOSER_REQUIRE) return false;
  const words = line.slice(COMPOSER_REQUIRE.length).split(" ").filter(Boolean);
  const required = words.find((word) => !word.startsWith("-"));
  return TOOLS.some((tool) => shown.has(tool.id) && onlyPackageOf(tool, stack) === required);
}

/**
 * The state of a row of the per-stack table, from its own cells and the ids of `TOOLS` that the
 * project's targets of the row's stack show: held with the reason of the first order that holds,
 * in the project already, or ready with the forms of its lines, each once, in their order.
 * `hostedLifted` reads the row with the hosted hold left out, as a person's consent leaves it.
 */
export function rowInstall(
  cells: readonly string[],
  shown: ReadonlySet<string>,
  hostedLifted = false,
): RowInstall {
  const lines = installSpans(cells);
  const reason = holdOf(cells, lines, hostedLifted);
  if (reason !== null) return { state: "held", reason };
  const forms = formsOf(lines);
  if (forms === null) return { state: "held", reason: HOLD.noForm };
  // A server's line is ready only where a declaration shows the server to only read (item 2026-11-26-005).
  const reads = (address: string) => READING_SERVERS.some((server) => server.address === address);
  if (
    lines.some((line) => {
      const server = serverLine(line);
      return server !== undefined && !reads(server.address);
    })
  )
    return { state: "held", reason: HOLD.notReading };
  const stack = STACK_OF.get(cells[0] ?? "");
  if (stack !== undefined && lines.some((line) => requiresShown(line, stack, shown)))
    return { state: "in the project already" };
  return { state: "ready", forms };
}

/** The lines printed after a row for its state: the engine's own words alone. */
export function installLines(install: RowInstall): string[] {
  if (install.state === "held") return [`  install: held, ${install.reason}`];
  if (install.state !== "ready") return [`  install: ${install.state}`];
  return ["  install: ready", ...install.forms.map(({ form, note }) => `    ${form}: ${note}`)];
}

/** The heading of the one table whose rows are keyed by stack. */
const PER_STACK = "### Per stack, from the framework's or the tool's own team";
/** The stack names of that table's first cell, each to the core's stack, in the declaration's order. */
const STACK_OF: ReadonlyMap<string, string> = new Map([
  ["PHP", "php"],
  ["Node / TypeScript", "node"],
  ["Python", "python"],
  ["Go", "go"],
  ["Rust", "rust"],
]);
/** The core's stacks the table has rows for, in the declaration's order. */
const ROW_STACKS: readonly string[] = [...STACK_OF.values()];
const isLetter = (char: string | undefined) => char !== undefined && /[A-Za-z]/.test(char);

/** The ids of the table that targets show between them. */
function shownIds(targets: readonly Pick<Target, "frameworks">[]): Set<string> {
  return new Set(targets.flatMap((target) => frameworkIds(target.frameworks)));
}

/** Whether a text names a phrase whole: the phrase with a letter on neither side of it. */
function names(text: string, phrase: string): boolean {
  for (let at = text.indexOf(phrase); at >= 0; at = text.indexOf(phrase, at + 1))
    if (!isLetter(text[at - 1]) && !isLetter(text[at + phrase.length])) return true;
  return false;
}

/** The ids of the tools' table that targets show between them. */
function shownTools(targets: readonly Pick<Target, "tools">[]): Set<string> {
  return new Set(targets.flatMap((target) => toolIds(target.tools)));
}

/**
 * The rows of the backend declaration's per-stack table, each marked for a project's targets. For
 * a row of a stack the project has, in this order: a framework of the stack named in its cell
 * decides (`framework` where a target shows one named, else `not this project's`); else a tool of
 * the stack named in its cell decides the same way (`tool`); else a product no manifest shows is
 * `not this project's`; else the row is the project's `by stack`. So a framework's row is a
 * project's whether or not the tool it installs is already there.
 */
export function projectRows(
  declaration: string,
  targets: readonly Pick<Target, "stack" | "frameworks" | "tools">[],
  /** The project's record: an entry of the backend's lifts the hosted hold of its row. */
  entries: readonly SourceEntry[] = [],
): ProjectRow[] {
  const section = declarationSections(declaration).find((s) => s.heading === PER_STACK);
  // The table's lines after its header: the rows, as the file holds them.
  const lines = (section?.lines ?? []).filter(isRow).slice(1);
  return lines.map((line): ProjectRow => {
    const row = cells(line);
    const stack = STACK_OF.get(row[0] ?? "");
    const mine = targets.filter((target) => target.stack === stack);
    const tools = shownTools(mine);
    const marked = (mark: RowMark): ProjectRow => ({
      mark,
      cells: row,
      line,
      ...recordedInstall(row, tools, PROJECT_TEAM, entries),
    });
    if (stack === undefined || mine.length === 0) return marked("other stack");
    const said = row[1] ?? "";
    const frameworks = FRAMEWORKS.filter((f) => f.stack === stack && names(said, f.name));
    if (frameworks.length) {
      const shown = shownIds(mine);
      return marked(frameworks.some((f) => shown.has(f.id)) ? "framework" : "not this project's");
    }
    const named = TOOLS.filter(
      (tool) => Object.hasOwn(tool.stacks, stack) && names(said, tool.name),
    );
    if (named.length)
      return marked(named.some((tool) => tools.has(tool.id)) ? "tool" : "not this project's");
    const product = NOT_IN_A_MANIFEST.some((entry) => names(said, entry.name));
    return marked(product ? "not this project's" : "by stack");
  });
}

/** The heading of the table whose rows are every stack's, and how its rows for an error service open. */
const COMMON = "### Common to every stack";
const ERROR_SERVICE = "Errors in production: ";

/** The rows of the common table for the error services a project's targets show, as the file holds them, in its order. */
function errorServiceRows(
  declaration: string,
  targets: readonly Pick<Target, "tools">[],
): string[] {
  const section = declarationSections(declaration).find((s) => s.heading === COMMON);
  const shown = shownTools(targets);
  return (section?.lines ?? [])
    .filter(isRow)
    .slice(1)
    .filter((line) => {
      const use = cells(line)[0] ?? "";
      if (!use.startsWith(ERROR_SERVICE)) return false;
      const service = use.slice(ERROR_SERVICE.length);
      return TOOLS.some((tool) => tool.name === service && shown.has(tool.id));
    });
}

/** A project's root and its targets whose stack the declaration has rows for, detected in memory; null where the folder is in no project. */
function detectedProject(cwd: string): { root: string; targets: Target[] } | null {
  const root = findRoot(cwd);
  if (root === null) return null;
  // No pack's rules: the stacks are the core's five, and nothing is loaded or saved.
  const targets = detectTargets(root).filter((target) => ROW_STACKS.includes(target.stack));
  return { root, targets };
}

/** The lines that describe a project: its stacks with their frameworks, and its tools where it shows any. */
function describedProject(targets: readonly Target[]): string[] {
  const stacks = CORE_STACKS.filter((stack) => targets.some((target) => target.stack === stack));
  const of = (stack: string) => targets.filter((target) => target.stack === stack);
  const frameworks = stacks.map((stack) => {
    const shown = shownIds(of(stack));
    const ids = FRAMEWORKS.filter((f) => shown.has(f.id)).map((f) => f.id);
    return `${stack} (${ids.length ? ids.join(", ") : "no framework of the table"})`;
  });
  const tools = stacks.flatMap((stack) => {
    const shown = shownTools(of(stack));
    const ids = TOOLS.filter((tool) => shown.has(tool.id)).map((tool) => tool.id);
    return ids.length ? [`${stack} (${ids.join(", ")})`] : [];
  });
  return [
    `this project: ${frameworks.join("; ")}`,
    ...(tools.length ? [`tools: ${tools.join("; ")}`] : []),
  ];
}

const UNREAD_RECORD = `the record of installs (${SOURCES_RECORD_NAME}) could not be read as the engine writes it and was not read`;

/** A count with its word: `0 rows`, `1 row`, `2 rows`. */
const rowsCount = (count: number) => `${count} row${count === 1 ? "" : "s"}`;

/** The day of an entry: the first ten characters of its time, which is its day in UTC. */
const dayOf = (entry: SourceEntry) => entry.at.slice(0, 10);

const sameLines = (a: readonly string[], b: readonly string[]) =>
  a.length === b.length && a.every((line, at) => line === b[at]);

/** A row as a form prints it: its cells, its state and what its hosted hold is. */
type StatedRow = Pick<ProjectRow, "cells" | "install" | "hosted">;

/** The decisions of an entry that lift a row's hosted hold: a consent, and an install, whose lines already ran at a person's yes. */
const LIFTING: readonly SourceDecision[] = ["consented", "installed"];

/**
 * A row's state with the project's record. A row whose first hold is the hosted one is read again
 * with that hold left out: where an entry of the row's own team at its page holds the row's lines
 * and a lifting decision, that second reading is the row's state; else the row stays held as hosted
 * and keeps the second reading, which says whether a consent would lift it.
 */
function recordedInstall(
  cells: readonly string[],
  shown: ReadonlySet<string>,
  team: string,
  entries: readonly SourceEntry[],
): Pick<ProjectRow, "install" | "hosted"> {
  const install = rowInstall(cells, shown);
  if (install.state !== "held" || install.reason !== HOLD.hosted) return { install };
  const lifted = rowInstall(cells, shown, true);
  const by = entries.find(
    (entry) =>
      entry.team === team &&
      entry.page === cells[2] &&
      LIFTING.includes(entry.decision) &&
      sameLines(entry.lines, installSpans(cells)),
  );
  if (by === undefined) return { install, hosted: { lifted } };
  return { install: lifted, hosted: { lifted, by } };
}

/** Whether a row is held as hosted and a consent would lift it: no entry lifts it, its page can be given, and nothing else holds it. */
function consentOffered(row: StatedRow): boolean {
  return (
    row.hosted !== undefined &&
    row.hosted.by === undefined &&
    row.hosted.lifted.state !== "held" &&
    (row.cells[2] ?? "") !== ""
  );
}

/** The entry a record holds for a row of a team's, by the row's page. */
function entryOf(
  entries: readonly SourceEntry[],
  team: string,
  row: StatedRow,
): SourceEntry | undefined {
  return entries.find((entry) => entry.team === team && entry.page === row.cells[2]);
}

/**
 * The lines printed after a row for its state, with the record: a ready row with an entry prints
 * the entry's decision and day where its lines are the row's, and ready again, said, where they
 * changed. A held row and a row in the project already print their state whatever the record holds.
 * A row held as hosted that a consent would lift prints how the consent is given, and a row a
 * consent made ready prints that it is hosted and the consent's day.
 */
function stateLines(
  row: StatedRow,
  entries: readonly SourceEntry[],
  team: string = PROJECT_TEAM,
): string[] {
  if (consentOffered(row))
    return [
      ...installLines(row.install),
      `    a person's consent for this project lifts this hold: crew sources ${team} --consented ${declarationLine(row.cells[2] ?? "")}`,
    ];
  const by = row.hosted?.by;
  if (by?.decision === "consented" && row.install.state === "ready")
    return [
      ...installLines(row.install),
      `    hosted: consented on ${dayOf(by)}; what a session asks of this server leaves the machine`,
    ];
  // A consent is no decision on an install: a row it did not make ready prints as a row with no entry.
  const recorded = row.install.state === "ready" ? entryOf(entries, team, row) : undefined;
  const entry = recorded?.decision === "consented" ? undefined : recorded;
  if (entry === undefined) return installLines(row.install);
  if (sameLines(entry.lines, installSpans(row.cells)))
    return [`  install: ${entry.decision}, recorded on ${dayOf(entry)}`];
  const [, ...notes] = installLines(row.install);
  return [
    `  install: ready, its line changed since it was recorded as ${entry.decision} on ${dayOf(entry)}`,
    ...notes,
  ];
}

/** The rows of a project under their headings, each with its state, what was left out of the per-stack table, and what the command cannot tell. */
function projectRowLines(
  declaration: string,
  targets: readonly Target[],
  entries: readonly SourceEntry[],
): string[] {
  const rows = projectRows(declaration, targets, entries);
  const of = (mark: RowMark) => rows.filter((row) => row.mark === mark);
  const orNone = (lines: string[]) => (lines.length ? lines : ["  none"]);
  const printed = (mark: RowMark) =>
    orNone(of(mark).flatMap((row) => [declarationLine(row.line), ...stateLines(row, entries)]));
  const held = installLines({ state: "held", reason: ERROR_SERVICE_HOLD });
  return [
    "rows for this project's frameworks:",
    ...printed("framework"),
    "rows for the tools this project shows:",
    ...printed("tool"),
    "rows by stack:",
    ...printed("by stack"),
    "error services this project shows:",
    "  a row here adds a server that reaches the service's production data with a credential, and a hosted one sends what a session asks off the machine; where the credential is held and with what scope is not decided: run no line of this section before it is",
    ...orNone(
      errorServiceRows(declaration, targets).flatMap((line) => [declarationLine(line), ...held]),
    ),
    `left out: ${rowsCount(of("other stack").length)} of another stack, ${rowsCount(of("not this project's").length)} of a framework, a tool or a product this project does not show`,
    "not told: the rows of the table Common to every stack for source hosting and databases, which depend on a service nothing detects",
  ];
}

/** The lines of `crew sources backend --project`, after the declaration's path. The two short answers hold nothing of a project's rows nor of its record. */
function projectLines(declaration: string, cwd: string): string[] {
  const project = detectedProject(cwd);
  if (project === null) return [NO_PROJECT];
  if (project.targets.length === 0)
    return [
      `this project: no target of a stack the declaration has rows for (${ROW_STACKS.join(", ")})`,
    ];
  const record = readSourcesRecord(project.root);
  return [
    ...describedProject(project.targets),
    ...projectRowLines(declaration, project.targets, record.entries),
    ...(record.unread ? [UNREAD_RECORD] : []),
  ];
}

/** The last cell of the header of a table whose rows are installs. */
const INSTALL_HEADER = "How it is installed";
/** How the heading opens of a section whose tables the definition leaves out or holds. */
const HELD_HEADINGS: readonly string[] = ["### Left out", "### Held"];
/** What a row says, in any cell, where something is owed before it enters. */
const OWED_PHRASES: readonly string[] = ["still owed", "to be checked"];
/** Why a row of a team other than the project team is held, beside the reasons of its own cells. */
const TEAM_HOLD = {
  heading: "its table is left out or held by the definition",
  owed: "its row says what is still owed or to be checked before it enters",
  otherTeam: "another team's declaration holds a row at its page",
} as const;
const NOT_TOLD_OF_A_TEAM =
  "not told: whether this project uses the tool or the service of a held row, and of a ready row save where the line under it says; the heading over a row says when it applies";

/** A row of an install table of a team's declaration, with the section it stands in and its state. */
interface TeamRow extends StatedRow {
  section: number;
  heading: string;
  line: string;
}

/**
 * The state of a row from its own declaration alone: held by its section's heading, then by what
 * it says is owed, then by its cells with no tool shown, since nothing detects a tool for it, and
 * with the record's entries of its team, which lift the hosted hold and no other.
 */
function ownInstall(
  heading: string,
  row: readonly string[],
  team: string,
  entries: readonly SourceEntry[],
): Pick<ProjectRow, "install" | "hosted"> {
  if (HELD_HEADINGS.some((opening) => heading.startsWith(opening)))
    return { install: { state: "held", reason: TEAM_HOLD.heading } };
  if (row.some((cell) => OWED_PHRASES.some((phrase) => names(cell.toLowerCase(), phrase))))
    return { install: { state: "held", reason: TEAM_HOLD.owed } };
  return recordedInstall(row, new Set(), team, entries);
}

/** The rows of a team's declaration's install tables in its order, each with its state from the declaration and the team's entries. */
function installRows(
  declaration: string,
  team: string,
  entries: readonly SourceEntry[],
): TeamRow[] {
  const found: TeamRow[] = [];
  for (const section of declarationSections(declaration)) {
    // A table is a run of lines that open with a pipe, its first line the header.
    let header: string[] | null = null;
    for (const line of section.lines) {
      if (!line.startsWith("|")) header = null;
      else if (header === null) header = cells(line);
      else if (isRow(line) && header.at(-1) === INSTALL_HEADER) {
        const row = cells(line);
        found.push({
          section: section.number,
          heading: section.heading,
          line,
          cells: row,
          ...ownInstall(section.heading, row, team, entries),
        });
      }
    }
  }
  return found;
}

/**
 * The rows of a team's install tables with their states, for a team other than the project team: a
 * row ready by its own declaration is held where another of those teams' declarations holds a row
 * at its page, since an install is the project's and not a team's. A declaration that cannot be
 * read refuses: the hold does not pass over it. An empty page is no page, and equals no other.
 * Each team's rows are read with its own entries first, so a hosted row a consent lifted holds no
 * other team's row, and a row lifted in one team is still held by another team's row at its page.
 */
function teamRows(
  root: string,
  team: string,
  declaration: string,
  entries: readonly SourceEntry[],
): TeamRow[] | { refused: string } {
  const heldPages = new Set<string>();
  for (const other of teamNames()) {
    if (other === team || other === PROJECT_TEAM) continue;
    const read = readTeamDeclaration(root, other);
    if ("refused" in read) return read;
    for (const row of installRows(read.text, other, entries)) {
      const page = row.cells[2] ?? "";
      if (row.install.state === "held" && page !== "") heldPages.add(page);
    }
  }
  return installRows(declaration, team, entries).map(
    (row): TeamRow =>
      row.install.state === "ready" && heldPages.has(row.cells[2] ?? "")
        ? { ...row, install: { state: "held", reason: TEAM_HOLD.otherTeam } }
        : row,
  );
}

/** The lines of `crew sources <team> --project` for a team other than the project team, after the declaration's path. */
function teamProjectLines(
  root: string,
  team: string,
  declaration: string,
  cwd: string,
): string[] | { refused: string } {
  const project = detectedProject(cwd);
  if (project === null) return [NO_PROJECT];
  const record = readSourcesRecord(project.root);
  const rows = teamRows(root, team, declaration, record.entries);
  if ("refused" in rows) return rows;
  const lines: string[] = [];
  let section = 0;
  for (const row of rows) {
    if (row.section !== section) lines.push(`${declarationLine(row.heading.replace(/^#+ /, ""))}:`);
    section = row.section;
    lines.push(declarationLine(row.line), ...stateLines(row, record.entries, team));
    // Whether the project shows the row's tool is said of a row a session may install, and of no other.
    if (row.install.state === "ready")
      lines.push(rowProjectLine(row.cells[2] ?? "", project.root, project.targets));
  }
  const ready = rows.filter((row) => row.install.state === "ready").length;
  return [
    ...lines,
    `ready: ${rowsCount(ready)}; held: ${rowsCount(rows.length - ready)}`,
    NOT_TOLD_OF_A_TEAM,
    ...(record.unread ? [UNREAD_RECORD] : []),
  ];
}

/** The marks of the rows a project may record: its own, by a framework, a tool or its stack. */
const OWN_MARKS: readonly RowMark[] = ["framework", "tool", "by stack"];
const NOT_RECORDED = {
  place: ".crew/local is not a folder of this project",
  bounds: "the row does not fit the record's bounds",
} as const;

/**
 * The one row of a team's form that is read at a page, with its line and the state the form prints
 * for it: the project team's among the rows that are the project's, another team's among the rows
 * of its install tables, where two rows at one page refuse since a record by its page would not
 * say which. `entries` are the record's, or none where the row is judged by the declaration alone.
 */
function recordedRow(
  root: string,
  team: string,
  declaration: string,
  targets: readonly Target[],
  page: string,
  entries: readonly SourceEntry[],
): (StatedRow & { line: string }) | { refused: string } {
  const noRow = {
    refused: `no row of this project is read at that page: crew sources ${team} --project prints the rows and their pages`,
  };
  if (team === PROJECT_TEAM)
    return (
      projectRows(declaration, targets, entries).find(
        (candidate) => OWN_MARKS.includes(candidate.mark) && candidate.cells[2] === page,
      ) ?? noRow
    );
  const rows = teamRows(root, team, declaration, entries);
  if ("refused" in rows) return rows;
  const [row, second] = rows.filter((candidate) => candidate.cells[2] === page);
  if (row === undefined) return noRow;
  if (second !== undefined)
    return {
      refused:
        "more than one row of this team is read at that page, so a record by its page would not say which",
    };
  return row;
}

/** The flags that record a row, each named after the decision it records. */
const RECORDING: readonly SourceDecision[] = ["installed", "declined", "consented"];

/**
 * `crew sources <team> --installed <page> | --declined <page> | --consented <page>`: one row of the
 * project's recorded by its page, at the time given. A consent is recorded for a row the
 * declaration alone holds as hosted and nothing else holds, whatever the record says of it; an
 * install and a refusal for a row the form calls ready, a hosted row a consent lifted among them. It refuses by the first case of the spec's table that holds, and
 * a refusal prints no row and no character of the page given. `root` is the plugin's folder and
 * `cwd` a folder of the project.
 */
export function recordSourcesCommand(
  root: string,
  args: readonly string[],
  flags: Readonly<Record<string, string | boolean>>,
  cwd: string,
  at: string,
): { code: number; text: string } {
  const refuse = (text: string) => ({ code: 1, text });
  // One of the three flags, and no more: which one is the decision, and its value the page.
  const given = RECORDING.filter((flag) => flags[flag] !== undefined);
  const [decision] = given;
  if (decision === undefined || given.length !== 1) return refuse(USAGE);
  const page = flags[decision];
  if (typeof page !== "string" || page === "") return refuse(USAGE);
  if (args.length !== 1 || flags.project !== undefined) return refuse(USAGE);
  const team = args[0] ?? "";
  const read = readTeamDeclaration(root, team);
  if ("refused" in read) return refuse(read.refused);
  const project = detectedProject(cwd);
  // The command reaches here in a project; a caller with a folder in none is told so.
  if (project === null) return refuse(NO_PROJECT);
  if (sourcesPlaceRefused(project.root)) return refuse(`not recorded: ${NOT_RECORDED.place}`);
  // A consent is judged with no entry read, so one that stands does not hide the hold it answers.
  const entries = decision === "consented" ? [] : readSourcesRecord(project.root).entries;
  const found = recordedRow(root, team, read.text, project.targets, page, entries);
  if ("refused" in found) return refuse(found.refused);
  const row = found;
  if (decision === "consented") {
    if (row.hosted === undefined)
      return refuse("not recorded: the row is not held for being hosted");
    if (row.hosted.lifted.state === "held")
      return refuse(
        `not recorded: with the hosted hold lifted the row is still held, ${row.hosted.lifted.reason}`,
      );
  } else if (row.install.state === "held")
    return refuse(`not recorded: the row is held, ${row.install.reason}`);
  else if (row.install.state === "in the project already")
    return refuse("not recorded: the row is in the project already");
  const recorded = recordSourceRow(
    project.root,
    { team, page, decision, lines: installSpans(row.cells) },
    at,
  );
  if (!recorded.ok) return refuse(`not recorded: ${NOT_RECORDED[recorded.why]}`);
  return {
    code: 0,
    text: [
      declarationLine(row.line),
      `recorded: ${recorded.entry.decision} on ${dayOf(recorded.entry)}`,
      ...(recorded.replaced
        ? [`it replaces: ${recorded.replaced.decision} on ${dayOf(recorded.replaced)}`]
        : []),
      ...(recorded.notKept
        ? [
            `the record that stood (${SOURCES_RECORD_NAME}) could not be read as the engine writes it and was not kept`,
          ]
        : []),
      LAST_LINE,
    ].join("\n"),
  };
}

/**
 * `crew sources [<team> [<n>]]`: the teams with their files, a team's index, or one section's own
 * lines; `crew sources <team> --project`: for the backend, the rows of its per-stack table that are
 * the project's at `cwd`; for another team, every row of its install tables with its state. Each ends with the fixed last line. A refusal carries no line of a declaration.
 */
export function sourcesCommand(
  root: string,
  args: readonly string[],
  /** `project`: the folder whose project's rows are asked for, with `--project`. */
  options: { project?: { cwd: string } } = {},
): { code: number; text: string } {
  const refuse = (text: string) => ({ code: 1, text });
  const done = (lines: string[]) => ({ code: 0, text: [...lines, LAST_LINE].join("\n") });
  if (args.length > 2) return refuse(USAGE);
  const [team, n] = args;
  // The project's rows are one team's and no section's.
  if (options.project && (team === undefined || n !== undefined)) return refuse(USAGE);
  if (team === undefined) {
    const lines: string[] = [];
    for (const name of teamNames()) {
      const read = readTeamDeclaration(root, name);
      if ("refused" in read) return refuse(read.refused);
      lines.push(`${name}: ${declarationSections(read.text).length} sections, ${read.path}`);
    }
    return done(lines);
  }
  const read = readTeamDeclaration(root, team);
  if ("refused" in read) return refuse(read.refused);
  if (options.project) {
    if (team === PROJECT_TEAM)
      return done([read.path, ...projectLines(read.text, options.project.cwd)]);
    const lines = teamProjectLines(root, team, read.text, options.project.cwd);
    return "refused" in lines ? refuse(lines.refused) : done([read.path, ...lines]);
  }
  const sections = declarationSections(read.text);
  if (n === undefined) return done([read.path, ...sections.map(indexLine)]);
  const section = /^[1-9]\d*$/.test(n) ? sections[Number(n) - 1] : undefined;
  if (!section)
    return refuse(
      `${team} has ${sections.length} sections: give a number from 1 to ${sections.length}`,
    );
  return done(section.lines.map(declarationLine));
}
